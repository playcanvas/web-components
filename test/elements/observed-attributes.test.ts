const observedBy = (tag: string) => {
    const element = customElements.get(tag) as unknown as { observedAttributes?: string[] };
    return element.observedAttributes ?? [];
};

describe('observed attributes', () => {
    it('pins the attributes of every tag in the golden list, and of no other', () => {
        expect(Object.keys(OBSERVED).sort()).toEqual([...TAGS].sort());
    });

    it.for([...TAGS].sort())('%s observes exactly the attributes pinned for it', (tag) => {
        expect([...observedBy(tag)].sort()).toEqual([...OBSERVED[tag]].sort());
    });

    it.for([...TAGS].sort())('%s observes no attribute twice', (tag) => {
        const observed = observedBy(tag);
        expect(new Set(observed).size).toBe(observed.length);
    });
});
